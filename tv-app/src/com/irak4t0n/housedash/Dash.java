package com.irak4t0n.housedash;

import android.content.ActivityNotFoundException;
import android.content.Context;
import android.content.Intent;
import android.content.SharedPreferences;
import android.graphics.Color;
import android.net.Uri;
import android.os.Handler;
import android.view.KeyEvent;
import android.view.View;
import android.webkit.ValueCallback;
import android.webkit.WebResourceError;
import android.webkit.WebResourceRequest;
import android.webkit.WebSettings;
import android.webkit.WebView;
import android.webkit.WebViewClient;

/** The one WebView both the screensaver and the app share. Loads the dashboard in TV mode,
 *  hides every bit of chrome, retries if the Pi is unreachable, and hands any link that is not
 *  the dashboard itself to the TV's browser (Silk / whatever is installed). */
final class Dash {
    static final String PREFS = "housedash";
    static final String KEY_URL = "url";
    static final String DEFAULT_URL = BuildConfig.DASHBOARD_URL;   // generated by build.sh from DASH_URL

    static String url(Context c) {
        SharedPreferences p = c.getSharedPreferences(PREFS, Context.MODE_PRIVATE);
        return p.getString(KEY_URL, DEFAULT_URL);
    }

    static void setUrl(Context c, String u) {
        c.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit().putString(KEY_URL, u).apply();
    }

    /** The dashboard URL with ?tv=1 so the page turns on remote-control mode. */
    static String tvUrl(Context c) {
        String u = url(c);
        return u + (u.contains("?") ? "&" : "?") + "tv=1";
    }

    static WebView make(Context c, Runnable onExternal) {
        final WebView w = new WebView(c);
        w.setBackgroundColor(Color.parseColor("#0b0f14"));
        w.setFocusable(false);
        w.setVerticalScrollBarEnabled(false);
        w.setHorizontalScrollBarEnabled(false);
        WebSettings s = w.getSettings();
        s.setJavaScriptEnabled(true);
        s.setDomStorageEnabled(true);
        s.setLoadWithOverviewMode(true);
        s.setUseWideViewPort(true);
        s.setCacheMode(WebSettings.LOAD_NO_CACHE);
        s.setMediaPlaybackRequiresUserGesture(false);
        RetryClient rc = new RetryClient(w); rc.onExternal = onExternal;
        w.setWebViewClient(rc);
        w.loadUrl(tvUrl(c));
        return w;
    }

    /** Map a remote key to the page's tvKey() name, or null if the page doesn't handle it. */
    static String keyName(int code) {
        switch (code) {
            case KeyEvent.KEYCODE_DPAD_LEFT: return "left";
            case KeyEvent.KEYCODE_DPAD_RIGHT: return "right";
            case KeyEvent.KEYCODE_DPAD_CENTER:
            case KeyEvent.KEYCODE_ENTER:
            case KeyEvent.KEYCODE_BUTTON_A: return "ok";
            case KeyEvent.KEYCODE_BACK:
            case KeyEvent.KEYCODE_ESCAPE: return "back";
            default: return null;
        }
    }

    /** Ask the page to handle a key; calls notHandled.run() if the page passed on it. */
    static void sendKey(WebView w, String name, final Runnable notHandled) {
        w.evaluateJavascript("(window.tvKey ? window.tvKey('" + name + "') : 'pass')", new ValueCallback<String>() {
            public void onReceiveValue(String v) {
                if (v == null || !v.contains("handled")) { if (notHandled != null) notHandled.run(); }
            }
        });
    }

    /** Open a link in the TV's own browser. */
    static boolean openExternal(Context c, String url) {
        try {
            Intent i = new Intent(Intent.ACTION_VIEW, Uri.parse(url));
            i.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);
            c.startActivity(i);
            return true;
        } catch (ActivityNotFoundException e) {
            return false;
        }
    }

    /** Keeps the WebView on the dashboard; anything else goes to the TV browser. Retries failed loads. */
    static final class RetryClient extends WebViewClient implements Runnable {
        private final WebView web;
        private final Handler h = new Handler();
        Runnable onExternal;   // set by the dream so it can end itself after launching the browser
        RetryClient(WebView w) { web = w; }

        private boolean isDashboard(String u) {
            String base = url(web.getContext());
            int i = base.indexOf("//"); String host = i >= 0 ? base.substring(i + 2) : base;
            int j = host.indexOf('/'); if (j >= 0) host = host.substring(0, j);
            return u.contains("//" + host);
        }

        @Override public boolean shouldOverrideUrlLoading(WebView v, WebResourceRequest r) {
            String u = r.getUrl().toString();
            if (isDashboard(u)) return false;
            openExternal(v.getContext(), u);
            if (onExternal != null) onExternal.run();
            return true;
        }

        @Override public void onReceivedError(WebView v, WebResourceRequest r, WebResourceError e) {
            if (!r.isForMainFrame()) return;
            v.loadData("<html><body style='background:#0b0f14;color:#8b98a8;font:28px system-ui;display:flex;"
                    + "align-items:center;justify-content:center;height:100vh;margin:0'>dashboard unreachable, retrying</body></html>",
                    "text/html", "utf-8");
            h.removeCallbacks(this);
            h.postDelayed(this, 15000);
        }
        public void run() { web.loadUrl(tvUrl(web.getContext())); }
    }

    static void fullscreen(View v) {
        v.setSystemUiVisibility(View.SYSTEM_UI_FLAG_FULLSCREEN | View.SYSTEM_UI_FLAG_HIDE_NAVIGATION
                | View.SYSTEM_UI_FLAG_IMMERSIVE_STICKY | View.SYSTEM_UI_FLAG_LAYOUT_STABLE);
    }
}

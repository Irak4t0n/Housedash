#!/bin/bash
# Build HouseDashboard.apk without Gradle: aapt2 -> javac -> d8 -> zipalign -> apksigner
#
#   DASH_URL=http://192.168.1.50:8088/ ./build.sh
#
# Needs: JDK 17+, Android SDK with build-tools 35.x and platforms/android-34 (sdkmanager or Android Studio).
# Signing: housedash.keystore next to this script. Make one once and KEEP it (updates must be signed with
# the same key or the TV refuses them):
#   keytool -genkeypair -v -keystore housedash.keystore -alias housedash -keyalg RSA -keysize 2048 \
#           -validity 10000 -storepass housedash -keypass housedash -dname "CN=housedash"
set -e
cd "$(dirname "$0")"
SDK=${ANDROID_SDK_ROOT:-${ANDROID_HOME:-$HOME/android-sdk}}
BT=$(ls -d "$SDK"/build-tools/35.* 2>/dev/null | tail -1); JAR=$SDK/platforms/android-34/android.jar
[ -n "$BT" ] || { echo "build-tools 35.x not found under $SDK (set ANDROID_SDK_ROOT)"; exit 1; }
[ -f housedash.keystore ] || { echo "no housedash.keystore - see the keytool line at the top of this script"; exit 1; }
URL=${DASH_URL:-http://housedash.local:8088/}
rm -rf build && mkdir -p build/gen/com/irak4t0n/housedash build/classes
cat > build/gen/com/irak4t0n/housedash/BuildConfig.java <<EOF
package com.irak4t0n.housedash;
/** Generated by build.sh. */
public final class BuildConfig { public static final String DASHBOARD_URL = "$URL"; private BuildConfig() {} }
EOF
"$BT/aapt2" compile --dir res -o build/res.zip
"$BT/aapt2" link -o build/unsigned.apk -I "$JAR" --manifest AndroidManifest.xml -R build/res.zip --java build/gen --auto-add-overlay
javac --release 8 -Xlint:-options -cp "$JAR" -d build/classes $(find build/gen src -name '*.java')
"$BT/d8" --release --lib "$JAR" --min-api 25 --output build $(find build/classes -name '*.class')
(cd build && zip -q -u unsigned.apk classes.dex)
"$BT/zipalign" -f 4 build/unsigned.apk build/aligned.apk
"$BT/apksigner" sign --ks housedash.keystore --ks-pass pass:${KS_PASS:-housedash} --out build/HouseDashboard.apk build/aligned.apk
echo "built build/HouseDashboard.apk for $URL"
echo "install:  adb connect <tv-ip>:5555 && adb install -r build/HouseDashboard.apk"
echo "screensaver:  adb shell settings put secure screensaver_components com.irak4t0n.housedash/.DashDream"

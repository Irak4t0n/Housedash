# Windows twin of build.sh: package the Roku screensaver (forward-slash zip entries, which Roku requires) and optionally sideload it.
#   .\build.ps1 -DashUrl http://192.168.4.99:8088/roku.png [-Interval 15] [-Roku 192.168.4.59 -RokuPass yourdevpassword]
param([string]$DashUrl = "http://housedash.local:8088/roku.png", [int]$Interval = 15, [string]$Roku = "", [string]$RokuPass = "", [string]$Out = "")
$ErrorActionPreference = "Stop"
Set-Location $PSScriptRoot
if (-not $Out) { $Out = Join-Path $PSScriptRoot "build\HouseDashboard-roku.zip" }
New-Item -ItemType Directory -Force (Split-Path $Out) | Out-Null
$utf8 = New-Object System.Text.UTF8Encoding $false
[IO.File]::WriteAllText("$PSScriptRoot\source\config.brs", "' generated by build.ps1`nfunction dashImageUrl() as String`n    return `"$DashUrl`"`nend function`nfunction dashInterval() as Integer`n    return $Interval`nend function`n", $utf8)
Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem
if (Test-Path $Out) { Remove-Item -Force $Out }
$zip = [System.IO.Compression.ZipFile]::Open($Out, [System.IO.Compression.ZipArchiveMode]::Create)
try {
  foreach ($f in (Get-ChildItem -Recurse -File -Path manifest, source, components, images)) {
    $rel = $f.FullName.Substring($PSScriptRoot.Length).TrimStart("\").Replace("\", "/")   # Windows PowerShell 5 has no GetRelativePath
    [System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile($zip, $f.FullName, $rel, [System.IO.Compression.CompressionLevel]::Optimal) | Out-Null
  }
} finally { $zip.Dispose() }
Remove-Item -Force "$PSScriptRoot\source\config.brs"
Write-Host "built $Out for $DashUrl"
if ($Roku) {
  if (-not $RokuPass) { throw "pass -RokuPass (the developer password you set on the TV)" }
  $r = curl.exe -s --digest -u "rokudev:$RokuPass" -F mysubmit=Install -F "archive=@$Out" "http://$Roku/plugin_install"
  ($r | Select-String -Pattern '<font[^>]*>([^<]*)</font>' -AllMatches).Matches | ForEach-Object { $_.Groups[1].Value } | Where-Object { $_ -notmatch 'appMsg' } | Write-Host
  Write-Host "now on the TV: Settings -> Screensaver -> House Dashboard"
}
